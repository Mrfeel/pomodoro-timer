w("")
w("### 量纲记忆")
w("$[B] = \\text{T} = \\text{N}/(\\text{A}\\cdot\\text{m})$。1T 是很大的磁场——地球磁场只有约 $0.5\\times 10^{-4}$T。")
w("")
w("## 「介质中的帮手」——磁场强度 $\\boldsymbol{H}$")
w("")
w("### 为什么要引入 $\\boldsymbol{H}$？")
w("")
w("与 $\\boldsymbol{D}$ 的引入动机完全对称：在磁介质中，安培环路定理本应是：")
w("$$\\oint \\boldsymbol{B}\\cdot d\\boldsymbol{l} = \\mu_0(I_f + I')$$")
