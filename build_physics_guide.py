w("")
w("**记忆方法**：$\\boldsymbol{S}=\\boldsymbol{E}\\times\\boldsymbol{H}$。右手定则：食指→$\\boldsymbol{E}$，中指→$\\boldsymbol{H}$，拇指→$\\boldsymbol{S}$（能量流动方向）。")
