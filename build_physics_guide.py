w("")
w("### 量纲记忆")
w("$[E] = \\text{N/C} = \\text{V/m}$。N/C 来自定义；V/m 来自 $E=-\\nabla\\varphi$。两者等价。")
w("")
w("## 「标量化的 $\\boldsymbol{E}$」——电势 $\\varphi$")
w("")
w("$$\\varphi(\\boldsymbol{r}) = \\int_{\\boldsymbol{r}}^{\\infty} \\boldsymbol{E}\\cdot d\\boldsymbol{l}$$")
w("")
w("- **物理意义**：把单位正电荷从 $\\boldsymbol{r}$ 移到无穷远，电场力做的功")
