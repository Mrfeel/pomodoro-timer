w("")
w("**记忆图像**：电势就像\"高度\"——电荷在电场中\"往下滑\"（从高电势到低电势）。$\\boldsymbol{E}$ 指向\"最陡的下坡方向\"。")
w("")
w("## 「介质中的帮手」——电位移矢量 $\\boldsymbol{D}$")
w("")
