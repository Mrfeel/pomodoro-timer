w("## 「力的传递者」——电场强度 $\\boldsymbol{E}$")
w("")
w("### 物理意义（最重要！）")
w("")
w("$$\\boldsymbol{E} = \\frac{\\boldsymbol{F}}{q_0}$$")
w("")
w("**$\\boldsymbol{E}$ 是单位正电荷所受的力。** 这是它的定义，也是理解一切电场问题的出发点。")
w("")
w("- 如果在空间某点放一个很小的正试探电荷 $q_0$，它受到的力除以 $q_0$ 就是该点的 $\\boldsymbol{E}$")
w("- $\\boldsymbol{E}$ 是矢量场：空间中每一点都有一个方向和大小")
w("- **静电场**中 $\\oint\\boldsymbol{E}\\cdot d\\boldsymbol{l}=0$——沿任意闭合回路走一圈，$\\boldsymbol{E}$ 做的总功为零（保守场）")
