w("### 与 $\\boldsymbol{B}$ 的对比")
w("| | $\\boldsymbol{B}$ | $\\boldsymbol{H}$ |")
w("|--|-----------|-----------|")
w("| 通量特性 | $\\oint\\boldsymbol{B}\\cdot d\\boldsymbol{S}=0$（无条件） | （无对应定理） |")
w("| 环量特性 | （含磁化电流） | $\\oint\\boldsymbol{H}\\cdot d\\boldsymbol{l}=I_f$（仅自由电流） |")
w("| 边界条件 | $B_n$ 连续（无磁荷） | $H_t$ 连续（无面自由电流时） |")
w("| 在线性介质中 | $\\boldsymbol{B}=\\mu_0\\mu_r\\boldsymbol{H}$ | — |")
w("")
w("## 「介质对磁场的反应」——磁化强度 $\\boldsymbol{M}$")
w("")
w("$$\\boldsymbol{M} = \\frac{\\sum_i \\boldsymbol{m}_i}{\\Delta V}$$")
w("")
w("- **物理图像**：外磁场使分子磁矩趋向排列→$\\boldsymbol{M}$ 是单位体积内的总磁矩")
w("- **$\\boldsymbol{M}$ 产生的电流**：体 $\\boldsymbol{j}'=\\nabla\\times\\boldsymbol{M}$（$\\boldsymbol{M}$ 不均匀处有体磁化电流）、面 $\\boldsymbol{i}'=\\boldsymbol{M}\\times\\hat{\\boldsymbol{n}}$（表面有面磁化电流）")
w("- 注意与 $\\boldsymbol{P}$ 对比：$\\rho'=-\\nabla\\cdot\\boldsymbol{P}$（散度）→ $\\boldsymbol{j}'=\\nabla\\times\\boldsymbol{M}$（旋度）。因为电荷是标量，电流是矢量。")
w("- **线性介质中**：$\\boldsymbol{M}=\\chi_m\\boldsymbol{H}$（顺磁质 $\\chi_m>0$；抗磁质 $\\chi_m<0$）。$\\mu_r=1+\\chi_m$")
w("")
w("## 「磁场的矢量势」——磁矢势 $\\boldsymbol{A}$")
w("")
w("$$\\boldsymbol{B} = \\nabla\\times\\boldsymbol{A}, \\quad \\nabla\\cdot\\boldsymbol{A}=0 \\;\\text{（库仑规范）}$$")
w("")
w("- **为什么引入 $\\boldsymbol{A}$？** $\\boldsymbol{A}$ 是矢量但只有一个方程（$\\nabla^2\\boldsymbol{A}=-\\mu_0\\boldsymbol{j}$），比直接处理 $\\boldsymbol{B}$ 的毕奥-萨伐尔积分更系统")
