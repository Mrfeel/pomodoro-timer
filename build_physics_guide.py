w("")
w("### 物理意义（最重要！）")
w("")
w("$$\\boldsymbol{F} = q\\boldsymbol{v}\\times\\boldsymbol{B} \\quad \\text{（洛伦兹磁力）}$$")
w("")
w("**$\\boldsymbol{B}$ 决定了运动电荷在磁场中受力的大小和方向。**")
w("")
w("- **$\\boldsymbol{B}$ 不作用在静止电荷上！** 这是电场和磁场的关键区别")
