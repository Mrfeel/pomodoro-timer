w("")
w("**记忆方法**：$\\boldsymbol{D}$ 的公式里 $\\boldsymbol{P}$ 前是 $+$，因为介质极化**增强**了 $\\boldsymbol{D}$（$\\varepsilon_r>1$）；$\\boldsymbol{H}$ 的公式里 $\\boldsymbol{M}$ 前是 $-$，因为磁化在定义 $\\boldsymbol{H}$ 时被\"减掉\"了。或者直接记线性关系：$\\boldsymbol{B}=\\mu_0\\mu_r\\boldsymbol{H}$ 和 $\\boldsymbol{D}=\\varepsilon_0\\varepsilon_r\\boldsymbol{E}$ 形式相同，无需记 $\\pm$。")
