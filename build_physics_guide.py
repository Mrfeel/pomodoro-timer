w("")
w("### 定义")
w("$$\\boldsymbol{D} = \\varepsilon_0\\boldsymbol{E} + \\boldsymbol{P}$$")
w("- $\\varepsilon_0\\boldsymbol{E}$：真空中的电场贡献")
w("- $\\boldsymbol{P}$：介质极化对 $\\boldsymbol{D}$ 的额外贡献")
w("- 在各向同性线性介质中：$\\boldsymbol{D} = \\varepsilon_0\\varepsilon_r\\boldsymbol{E}$（$\\boldsymbol{D}\\parallel\\boldsymbol{E}$，方向相同！）")
w("")
w("### 与 $\\boldsymbol{E}$ 的对比")
w("| | $\\boldsymbol{E}$ | $\\boldsymbol{D}$ |")
w("|--|-----------|-----------|")
w("| 通量源 | 所有电荷（自由+极化） | **仅自由电荷** |")
w("| 边界条件 | $E_t$ 连续 | $D_n$ 连续（无自由面电荷时） |")
w("| 在介质界面上 | 一般不连续 | 法向连续 |")
w("")
w("## 「介质对电场的反应」——极化强度 $\\boldsymbol{P}$")
w("")
w("$$\\boldsymbol{P} = \\frac{\\sum_i \\boldsymbol{p}_i}{\\Delta V}$$")
w("")
w("- **物理图像**：外电场使介质分子中的正负电荷中心分离→形成电偶极子→$\\boldsymbol{P}$ 是单位体积内的总电偶极矩")
w("- **$\\boldsymbol{P}$ 产生的电荷**：体 $\\rho'=-\\nabla\\cdot\\boldsymbol{P}$（$\\boldsymbol{P}$ 不均匀处有体极化电荷）、面 $\\sigma'=\\boldsymbol{P}\\cdot\\hat{\\boldsymbol{n}}$（表面有面极化电荷）")
w("- **线性介质中**：$\\boldsymbol{P} = \\chi_e\\varepsilon_0\\boldsymbol{E}$（$\\boldsymbol{P}\\parallel\\boldsymbol{E}$）")
w("- **$\\chi_e$（电极化率）** 反映介质容易被极化的程度。$\\chi_e>0$，$\\varepsilon_r=1+\\chi_e>1$")
