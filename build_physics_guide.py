# 公式记忆法
# ================================================================
w("\\newpage")
w("# 第五部分：公式记忆的系统方法")
w("")
w("## 方法一：从\"源→场→力\"逻辑链推导")
w("")
w("**电场链**：电荷分布 $\\rho(\\boldsymbol{r})$ →（库仑定律+叠加）→ $\\boldsymbol{E}(\\boldsymbol{r})$ →（$\\boldsymbol{F}=q\\boldsymbol{E}$）→ 力")
w("")
w("**磁场链**：电流分布 $\\boldsymbol{j}(\\boldsymbol{r})$ →（毕奥-萨伐尔定律+叠加）→ $\\boldsymbol{B}(\\boldsymbol{r})$ →（$\\boldsymbol{F}=q\\boldsymbol{v}\\times\\boldsymbol{B}$）→ 力")
w("")
w("**记住这两个\"链\"，就能把孤立的公式串联起来。**")
w("")
w("## 方法二：利用对称性\"批量记忆\"")
w("")
w("1. **$C$ 的公式→$L$ 的公式**：同轴电缆 $C=\\frac{2\\pi\\varepsilon_0 l}{\\ln(b/a)}$ → $L=\\frac{\\mu_0 l}{2\\pi}\\ln\\frac{b}{a}$。注意 $\\varepsilon_0\\leftrightarrow\\mu_0$，位置对调（一个在分子，一个在分母前的系数中）。")
w("")
w("2. **平板电容→螺线管电感**：$C=\\varepsilon_0 S/d$ → $L=\\mu_0 n^2 Sl$。$S$（面积）、$l$（长度）、$\\varepsilon_0\\leftrightarrow\\mu_0$。")
w("")
w("3. **$D_n$ 连续 ↔ $B_n$ 连续**（法向边界条件）；**$E_t$ 连续 ↔ $H_t$ 连续**（切向边界条件，无自由源时）。")
w("")
w("## 方法三：从\"能量\"反推\"力\"和\"电路参数\"")
w("")
